package com.example.frontend.ui.theme

import androidx.compose.ui.unit.dp

/** Shared layout spacing so every screen uses the same rhythm. */
object Spacing {
    /** Outer margin of a screen. */
    val screen = 20.dp
    /** Gap between two unrelated blocks. */
    val section = 20.dp
    /** Inner padding of a card. */
    val card = 16.dp
    /** Gap between repeated items, such as cards in a list. */
    val item = 12.dp
    /** Gap between a heading and its supporting line. */
    val small = 8.dp
    /** Gap inside a tightly grouped pair of lines. */
    val tight = 4.dp
}
